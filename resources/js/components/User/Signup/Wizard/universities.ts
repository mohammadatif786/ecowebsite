export const universityRegions = ["Caribbean", "United States", "Canada", "UK & Europe", "Latin America", "Africa", "Asia & Oceania"] as const;

const usStates = /, (A[LKZR]|C[AOT]|D\.C\.|DE|FL|GA|HI|I[ADLN]|K[SY]|LA|M[ADEINOST]|N[CDEHJMVY]|O[HKR]|PA|RI|S[CD]|T[NX]|UT|V[AT]|W[AIVY])$/;
const canada = /, (AB|BC|MB|NB|NL|NS|ON|PE|QC|SK)$/;

/**
 * The country a listed school is in, as the UVibes campus list spells it. Null when the
 * location isn't a single country (e.g. "Caribbean-wide").
 */
export function universityCountry(location: string, region: string): string | null {
    if (region === 'United States' || usStates.test(location) || location === 'Washington, D.C.') return 'United States';
    if (region === 'Canada' || canada.test(location)) return 'Canada';
    const last = location.split(',').pop()!.trim();
    if (last === 'UK') return 'United Kingdom';
    if (last === 'Caribbean-wide' || last.includes(' and Martinique')) return null;
    return last;
}
